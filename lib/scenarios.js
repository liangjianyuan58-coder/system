export const SCENARIOS = [
  '電話に出た瞬間、何も言わずにガチャ切りされた。',
  '30件架電して、アポゼロ。隣の新人は午前中に2件取れている。',
  '「二度とかけてくるな」と強い口調で怒鳴られて電話を切られた。',
  '朝から同じトークスクリプトを100回読み上げて、声も気持ちも擦り切れてきた。',
  '受注できたと思った案件が、上長確認でひっくり返された。',
  '提出したロープレ動画を、先輩からダメ出しだらけで突き返された。',
  '窓の外は快晴で遊んでいる人だらけ。自分はオフィスでひたすら架電。',
  'あと1件で日次目標達成なのに、終業まで残り5分しかない。',
  '同期が先に表彰され、自分の名前は最後まで呼ばれなかった。',
  '渾身のトークをしたのに「結構です」の一言で即断られた。',
  '雨で客先アポが2件連続ドタキャン。移動だけで1日が終わった。',
  '完璧に練習したのに、本番で頭が真っ白になって噛みまくった。',
];

export function randomScenario(exclude) {
  const pool = exclude ? SCENARIOS.filter((s) => s !== exclude) : SCENARIOS;
  return pool[Math.floor(Math.random() * pool.length)];
}
